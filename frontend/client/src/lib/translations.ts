/** Every key must exist in every supported locale — a missing key is a bug, not a fallback. */
export function assertTranslationsComplete(): string[] {
  const locales = Object.keys(TRANSLATIONS) as Locale[];
  const base = new Set(Object.keys(TRANSLATIONS[locales[0]]));
  const missing: string[] = [];
  for (const locale of locales.slice(1)) {
    for (const key of Array.from(base)) {
      if (!(key in TRANSLATIONS[locale])) missing.push(`${locale}:${key}`);
    }
  }
  return missing;
}
